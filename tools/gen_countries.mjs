// Regenerates backend/countries.py from app/profile-logic.ts so the form and the server share one list.
// Run: node tools/gen_countries.mjs
import { writeFileSync } from 'node:fs';
import * as L from '../app/profile-logic.ts';

const aliases = {};
for (const alias of ['usa', 'us', 'u.s.', 'u.s.a.', 'america', 'united states of america', 'uk', 'u.k.', 'great britain', 'england', 'britain', 'uae', 'korea', 'republic of korea',
  'czechia', 'türkiye', 'turkiye', 'russian federation', 'viet nam', 'burma', "cote d'ivoire", 'republic of india']) aliases[alias] = L.normalizeCountry(alias);

const py = (s) => JSON.stringify(s);
const lines = [
  '"""Countries the profile form offers. Generated by tools/gen_countries.mjs from app/profile-logic.ts; do not edit by hand."""',
  '',
  'COUNTRIES=[',
  ...L.COUNTRY_TABLE.map(([name, code]) => `    (${py(name)},${py(code)}),`),
  ']',
  'NAMES=[name for name,_ in COUNTRIES]',
  'ALIASES={',
  ...Object.entries(aliases).map(([k, v]) => `    ${py(k)}:${py(v)},`),
  '}',
  '',
  'def canonical_country(value):',
  '    """The official country name for what was typed or saved earlier (\'india\', \'USA\'), or None when it is not a country."""',
  "    text=(value or '').strip().casefold()",
  '    if not text:return None',
  '    for name in NAMES:',
  '        if name.casefold()==text:return name',
  '    return ALIASES.get(text)',
  '',
];
writeFileSync(new URL('../backend/countries.py', import.meta.url), lines.join('\n'));
console.log('wrote', L.COUNTRY_TABLE.length, 'countries and', Object.keys(aliases).length, 'aliases');
